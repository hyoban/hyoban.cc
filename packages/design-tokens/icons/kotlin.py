# Writes the Android app's ui/design/AppIcons.kt from icons.py (python3 packages/design-tokens/icons/kotlin.py): each icon an ImageVector of stroked (the set's
# STROKE, round) and filled paths, circles, rects and lines turned into path data; a fill may be even-odd, to cut holes.
import importlib.util, os

from svg import MIRROR, to_path

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('icons', os.path.join(HERE, 'icons.py'))
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)



def camel(name):
    return ''.join(p.capitalize() for p in name.split('-'))


out = [('''package cc.hyoban.moments.ui.design

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// The app's own icons, as the design system draws them (its Icons group): a 24 grid, lines
// {STROKE} wide with round ends and joins, a few filled marks. Drawn in black and tinted where
// they are shown, so each takes the colour of the text around it. Generated by
// packages/design-tokens/icons/kotlin.py from icons.py there, the design system's source too.

/**
 * One icon: [strokes] drawn as lines, [fills] filled and [holed] filled even-odd, so a shape inside cuts a hole;
 * [mirror] for those that point a way, turned round right to left.
 */
private fun icon(name: String, mirror: Boolean, strokes: List<String>, fills: List<String> = emptyList(), holed: List<String> = emptyList()): ImageVector {
    val builder = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = mirror)
    strokes.forEach {
        builder.addPath(addPathNodes(it), stroke = SolidColor(Color.Black), strokeLineWidth = {STROKE}f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)
    }
    fills.forEach { builder.addPath(addPathNodes(it), fill = SolidColor(Color.Black)) }
    holed.forEach { builder.addPath(addPathNodes(it), fill = SolidColor(Color.Black), pathFillType = PathFillType.EvenOdd) }
    return builder.build()
}

object AppIcons {''').replace('{STROKE}', '%g' % m.STROKE)]
for group, icons in m.GROUPS.items():
    out.append(f'    // {group}')
    for name, els in icons.items():
        paths = [to_path(e) for e in els]
        strokes = [d for d, f in paths if not f]
        fills = [d for d, f in paths if f is True]
        holed = [d for d, f in paths if f == 'evenodd']
        s = ', '.join(f'"{d}"' for d in strokes)
        f = ', '.join(f'"{d}"' for d in fills)
        fill_arg = f', listOf({f})' if fills or holed else ''
        if holed:
            fill_arg += ', listOf(' + ', '.join(f'"{d}"' for d in holed) + ')'
        out.append(f'    val {camel(name)}: ImageVector by lazy {{ icon("{name}", {"true" if name in MIRROR else "false"}, listOf({s}){fill_arg}) }}')
    out.append('')
out[-1] = '}'
path = os.path.join(HERE, '../../../apps/android/shared/src/commonMain/kotlin/cc/hyoban/moments/ui/design/AppIcons.kt')
open(path, 'w').write('\n'.join(out) + '\n')
print('wrote', sum(len(v) for v in m.GROUPS.values()))
