# Writes the Android app's ui/design/Stickers.kt from stickers.py
# (python3 packages/design-tokens/stickers/kotlin.py): each sticker its layers, back to front, as
# path data with a fill, a stroke and its width, which the viewer draws with Compose and saving
# draws into the photo with Android's own canvas.
import importlib.util, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'icons'))
from svg import num, to_path  # noqa: E402

spec = importlib.util.spec_from_file_location('stickers', os.path.join(HERE, 'stickers.py'))
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

OUT = os.path.join(HERE, '..', '..', '..', 'apps', 'android', 'shared', 'src', 'commonMain', 'kotlin',
                   'cc', 'hyoban', 'moments', 'ui', 'design', 'Stickers.kt')


def colour(value):
    if value in (None, 'none'):
        return 'null'
    return '0xFF' + value.lstrip('#').upper()


def layer(el):
    tag = re.match(r'<(\w+)', el).group(1)
    a = dict(re.findall(r'([\w-]+)="([^"]*)"', el))
    if tag == 'ellipse':
        cx, cy, rx, ry = (float(a[k]) for k in ('cx', 'cy', 'rx', 'ry'))
        d = (f'M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0'
             f'a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0z')
    else:
        d, _ = to_path(el)
    width = float(a.get('stroke-width', 0)) if a.get('stroke') else 0
    return f'StickerLayer("{d}", {colour(a.get("fill"))}, {colour(a.get("stroke"))}, {num(width)}f)'


entries = []
for plate, stickers in ((False, m.STICKERS), (True, m.PLATE_STICKERS)):
    for name, layers in stickers.items():
        width, height = (m.PLATE_WIDTH, m.PLATE_HEIGHT) if plate else (24, 24)
        cover = m.COVERS[name] if plate else m.FACE_COVER
        body = ',\n'.join(f'            {layer(el)}' for el in layers)
        args = ', '.join(f'{num(v)}f' for v in (width, height) + tuple(cover))
        key = name.replace('_', '-')
        entries.append(f'    {name.upper()}(\n        "{key}",\n        {"true" if plate else "false"},\n        {args},\n'
                       f'        listOf(\n{body},\n        ),\n    )')

text = '''package cc.hyoban.moments.ui.design

// The stickers 打码 lays over a face or a license plate, as the design system draws them (its
// Stickers card): generated by packages/design-tokens/stickers/kotlin.py from stickers.py there.
// Never edit by hand.

/** One layer of a sticker: [path] on the sticker's grid, filled with [fill] and stroked [width] wide with [stroke], each an ARGB colour or none. */
class StickerLayer(val path: String, val fill: Long?, val stroke: Long?, val width: Float)

/**
 * A sticker by the [key] a patch keeps, for a license [plate] or else a face, drawn on a grid
 * [width] by [height] with its corner at [GRID_ORIGIN] and the die-cut edge round it, its [layers]
 * back to front, a white die-cut edge first. It is solid over the box at [coverLeft], [coverTop],
 * [coverWidth] by [coverHeight]: drawn over a patch, that box takes in the whole patch, centred on it.
 */
enum class Sticker(
    val key: String,
    val plate: Boolean,
    val width: Float,
    val height: Float,
    val coverLeft: Float,
    val coverTop: Float,
    val coverWidth: Float,
    val coverHeight: Float,
    val layers: List<StickerLayer>,
) {
''' + ',\n'.join(entries) + ''',
    ;

    /** How large the sticker is drawn over a patch [patchWidth] by [patchHeight]: the scale from its grid. */
    fun scaleOver(patchWidth: Float, patchHeight: Float): Float = maxOf(patchWidth / coverWidth, patchHeight / coverHeight)

    companion object {
        /** Where every sticker's grid starts, the die-cut edge reaching a unit past it on each side. */
        const val GRID_ORIGIN = %sf

        fun of(key: String?): Sticker? = entries.firstOrNull { it.key == key }

        /** The stickers for a [plate] or else a face. */
        fun forPlate(plate: Boolean): List<Sticker> = entries.filter { it.plate == plate }

        /** A sticker for a [plate] or else a face at random, one of those not in [used] while any is left. */
        fun random(used: Collection<String> = emptyList(), plate: Boolean = false): String =
            forPlate(plate).let { all -> all.filter { it.key !in used }.ifEmpty { all } }.random().key
    }
}
''' % num(-1)
open(OUT, 'w').write(text)
print('wrote', len(entries))
